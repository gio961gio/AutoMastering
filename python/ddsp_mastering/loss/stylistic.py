"""Stylistic Reference Aggregate Perceptual Loss Module.

Computes psychoacoustically grounded aggregate feature distances between
different musical tracks, strictly avoiding point-to-point waveform comparison
and time-alignment artifacts.
"""

from typing import Dict, Optional, Tuple
import math
import torch
import torch.nn as nn
import torchaudio.functional as taf

from ddsp_mastering.loss.loudness import DifferentiableLoudnessLoss
from ddsp_mastering.loss.erb import ERBSpectralLoss
from ddsp_mastering.param_space import Z_NEUTRAL


class AggregatePerceptualLoss(nn.Module):
    """Aggregate statistical and perceptual distance loss for stylistic mastering.

    Compares long-term distributional descriptors between two distinct musical works:
      1. Mel-scale (`mel40`, V0/V0p) or ERB-48 multi-statistic (`erb48`, V1) spectral envelope distribution.
      2. Integrated & short-term ITU-R BS.1770-4 Loudness (LUFS).
      3. Dynamic Range & Crest Factor (Peak-to-Loudness Ratio / PLR).
      4. Mid/Side Stereo energy distribution & width.
      5. Parameter regularization prior towards conservative neutral preset.
    """

    def __init__(
        self,
        sample_rate: float = 48000.0,
        n_mels: int = 40,
        n_fft: int = 2048,
        hop_length: int = 512,
        weight_spectral: float = 1.0,
        weight_loudness: float = 0.8,
        weight_dynamics: float = 0.5,
        weight_stereo: float = 0.3,
        weight_param_reg: float = 0.02,
        spectral_mode: str = "mel40",
        weight_de_harsh: float = 0.0,
    ):
        super().__init__()
        if spectral_mode not in ("mel40", "erb48"):
            raise ValueError(f"Unsupported spectral_mode '{spectral_mode}'. Expected 'mel40' or 'erb48'.")
        self.sample_rate = sample_rate
        self.n_mels = n_mels
        self.n_fft = n_fft
        self.hop_length = hop_length
        self.spectral_mode = spectral_mode
        self.weight_de_harsh = weight_de_harsh

        self.weight_spectral = weight_spectral
        self.weight_loudness = weight_loudness
        self.weight_dynamics = weight_dynamics
        self.weight_stereo = weight_stereo
        self.weight_param_reg = weight_param_reg

        # Mel filterbank: [n_freqs, n_mels]
        n_freqs = n_fft // 2 + 1
        fb = taf.melscale_fbanks(
            n_freqs=n_freqs,
            f_min=20.0,
            f_max=min(20000.0, sample_rate * 0.499),
            n_mels=n_mels,
            sample_rate=int(sample_rate),
        )
        self.register_buffer("mel_fbanks", fb)  # [n_freqs, n_mels]
        self.register_buffer("stft_window", torch.hann_window(n_fft))

        eff_dh_ratio = (weight_de_harsh / weight_spectral) if weight_spectral > 0.0 else weight_de_harsh
        self.erb_loss = ERBSpectralLoss(
            sample_rate=sample_rate,
            weight_de_harsh=eff_dh_ratio,
        )
        self.loudness_loss = DifferentiableLoudnessLoss(sample_rate=sample_rate)

    def _extract_mel_spectrum_distribution(self, audio: torch.Tensor) -> torch.Tensor:
        """Compute long-term average log-Mel energy distribution [B, n_mels] via incoherent stereo power."""
        # audio: [B, C, T] where C=2 (stereo) or C=1 (mono)
        if audio.ndim == 2:
            audio = audio.unsqueeze(1)
        B, C, T = audio.shape

        # Flatten B and C for batched STFT
        audio_flat = audio.reshape(B * C, T)
        stft_res = torch.stft(
            audio_flat,
            n_fft=self.n_fft,
            hop_length=self.hop_length,
            window=self.stft_window,
            return_complex=True,
        )
        # Power spectrum for each channel: [B, C, n_freqs, num_frames]
        mag_sq_all = (torch.abs(stft_res) ** 2).reshape(B, C, -1, stft_res.shape[-1])
        # Incoherent stereo power: 0.5 * (|STFT_L|^2 + |STFT_R|^2)
        if C == 2:
            mag_sq = 0.5 * (mag_sq_all[:, 0, :, :] + mag_sq_all[:, 1, :, :])
        else:
            mag_sq = mag_sq_all[:, 0, :, :]

        # Project onto Mel scale: [B, num_frames, n_freqs] @ [n_freqs, n_mels] -> [B, num_frames, n_mels]
        mel_energy = torch.matmul(mag_sq.transpose(-1, -2), self.mel_fbanks)  # [B, num_frames, n_mels]

        # Temporal average across frames
        avg_mel = torch.mean(mel_energy, dim=-2)  # [B, n_mels]
        log_mel = torch.log(avg_mel + 1e-7)

        # Normalize energy level to isolate spectral tilt / shape from overall volume
        log_mel_shape = log_mel - torch.mean(log_mel, dim=-1, keepdim=True)
        return log_mel_shape

    def forward(
        self,
        pred_audio: torch.Tensor,
        ref_audio: torch.Tensor,
        normalized_params: Optional[torch.Tensor] = None,
        target_lufs: Optional[float] = None,
        mix_anchor_audio: Optional[torch.Tensor] = None,
    ) -> Tuple[torch.Tensor, Dict[str, float]]:
        """Compute multi-feature aggregate distance for stylistic reference mastering.

        Args:
            pred_audio: Audio generated by the DDSP mastering chain [B, 2, T_pred].
            ref_audio: Target reference song audio [B, 2, T_ref] (lengths may differ!).
            normalized_params: Latent controls z in [0, 1]^41 for regularization.
            target_lufs: Optional explicit target LUFS (overrides reference LUFS).
            mix_anchor_audio: Optional unoptimized mix chunk `x_mix` used to anchor
                              active-frame selection (`no_grad`) in `erb48` mode.

        Returns:
            Tuple of (total_loss, metrics_dict).
        """
        metrics: Dict[str, float] = {}
        total_loss = torch.tensor(0.0, device=pred_audio.device, dtype=pred_audio.dtype)

        # 1. Tonal Balance: Mel-40 (V0/V0p) or ERB-48 Multi-Statistic (V1/V1b)
        if self.spectral_mode == "erb48":
            erb_total, erb_metrics = self.erb_loss.forward_stylistic(
                pred_audio=pred_audio,
                ref_audio=ref_audio,
                mix_anchor_audio=mix_anchor_audio,
            )
            metrics.update(erb_metrics)
            metrics["stylistic_spectral_loss"] = erb_metrics["erb_stylistic_total_loss"]
            scale = self.weight_spectral if self.weight_spectral > 0.0 else 1.0
            total_loss = total_loss + scale * erb_total
        else:
            mel_pred = self._extract_mel_spectrum_distribution(pred_audio)
            with torch.no_grad():
                mel_ref = self._extract_mel_spectrum_distribution(ref_audio)

            spectral_diff = torch.mean(torch.abs(mel_pred - mel_ref))
            metrics["stylistic_spectral_loss"] = spectral_diff.item()
            total_loss = total_loss + self.weight_spectral * spectral_diff

        # 2. Loudness Matching Loss (ITU-R BS.1770-4)
        pred_lufs = self.loudness_loss.calculate_lufs(pred_audio)
        if target_lufs is not None:
            effective_target_lufs = torch.tensor(target_lufs, device=pred_audio.device, dtype=pred_audio.dtype)
        else:
            with torch.no_grad():
                effective_target_lufs = self.loudness_loss.calculate_lufs(ref_audio)

        lufs_loss = torch.mean((pred_lufs - effective_target_lufs) ** 2)
        metrics["stylistic_lufs_loss"] = lufs_loss.item()
        metrics["pred_lufs"] = pred_lufs.mean().item()
        metrics["ref_lufs"] = effective_target_lufs.mean().item()
        total_loss = total_loss + self.weight_loudness * lufs_loss

        # 3. Dynamic Profile / Crest Factor (PLR) Matching
        pred_plr = self.loudness_loss.calculate_plr(pred_audio)
        with torch.no_grad():
            ref_plr = self.loudness_loss.calculate_plr(ref_audio)

        plr_loss = torch.mean((pred_plr - ref_plr) ** 2)
        metrics["stylistic_plr_loss"] = plr_loss.item()
        metrics["pred_plr"] = pred_plr.mean().item()
        metrics["ref_plr"] = ref_plr.mean().item()
        total_loss = total_loss + self.weight_dynamics * plr_loss

        # 4. Stereo Width & Mid-Side Energy Balance Matching
        # pred
        left_p = pred_audio[:, 0, :]
        right_p = pred_audio[:, 1, :]
        mid_p = (left_p + right_p) * 0.70710678
        side_p = (left_p - right_p) * 0.70710678
        ms_ratio_pred = torch.log(torch.mean(side_p ** 2, dim=-1) + 1e-6) - torch.log(torch.mean(mid_p ** 2, dim=-1) + 1e-6)

        # ref
        with torch.no_grad():
            left_r = ref_audio[:, 0, :]
            right_r = ref_audio[:, 1, :]
            mid_r = (left_r + right_r) * 0.70710678
            side_r = (left_r - right_r) * 0.70710678
            ms_ratio_ref = torch.log(torch.mean(side_r ** 2, dim=-1) + 1e-6) - torch.log(torch.mean(mid_r ** 2, dim=-1) + 1e-6)

        stereo_diff = torch.mean(torch.abs(ms_ratio_pred - ms_ratio_ref))
        metrics["stylistic_stereo_loss"] = stereo_diff.item()
        total_loss = total_loss + self.weight_stereo * stereo_diff

        # 5. Parameter Regularization Prior
        if normalized_params is not None:
            z_target = Z_NEUTRAL.to(device=normalized_params.device, dtype=normalized_params.dtype)
            param_reg = torch.mean((normalized_params - z_target) ** 2)
            metrics["param_reg_loss"] = param_reg.item()
            total_loss = total_loss + self.weight_param_reg * param_reg

        metrics["mastering_loss_total"] = total_loss.item()
        return total_loss, metrics
